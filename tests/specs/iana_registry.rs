//! Validation against the IANA IPFIX registries
//!
//! The IANA "IPFIX Information Elements" registry is machine-readable, so the
//! Information Element table in `src/registry/information_elements.rs` is
//! *generated* from it (`make registry-update`) and *validated* against it
//! (`make specs-validate`). The validation fails when IANA assigns, changes or
//! deprecates an element, which is the signal to regenerate.
//!
//! The data types, data type semantics, Set IDs and Version Numbers
//! sub-registries are hand-written in `src/registry/mod.rs` and validated
//! against the IANA XML registry.

use super::download::{fetch, IANA_INFORMATION_ELEMENTS, IANA_IPFIX_REGISTRY};
use ipfix_parser::registry::{
    DataType, DataTypeSemantics, Status, INFORMATION_ELEMENTS, IPFIX_VERSION, MIN_DATA_SET_ID,
    OPTIONS_TEMPLATE_SET_ID, TEMPLATE_SET_ID,
};
use regex::Regex;
use std::collections::BTreeMap;
use std::fmt::Write;
use std::path::Path;

/// An Information Element row of the IANA CSV registry
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct IanaInformationElement {
    pub id: u16,
    pub name: String,
    pub data_type: String,
    pub semantics: Option<String>,
    pub status: String,
    pub units: Option<String>,
}

/// Rows that are not Information Elements
const NON_ELEMENT_NAMES: &[&str] = &[
    "Reserved",
    "Unassigned",
    "Assigned for NetFlow v9 compatibility",
];

/// Parse the IANA CSV registry, keeping the assigned Information Elements.
///
/// Rows with an ID range (e.g. `105-127`), a placeholder name, or no abstract
/// data type (ElementIDs 416 and 419, deprecated without a name) are skipped:
/// they cannot appear in a Template as a decodable element.
pub fn parse_iana_csv(csv: &str) -> Vec<IanaInformationElement> {
    let mut reader = csv::Reader::from_reader(csv.as_bytes());
    let headers = reader.headers().expect("Missing CSV headers").clone();
    let column = |name: &str| {
        headers
            .iter()
            .position(|h| h == name)
            .unwrap_or_else(|| panic!("Missing CSV column {}", name))
    };
    let (c_id, c_name, c_type, c_sem, c_status, c_units) = (
        column("ElementID"),
        column("Name"),
        column("Abstract Data Type"),
        column("Data Type Semantics"),
        column("Status"),
        column("Units"),
    );
    let non_empty = |s: &str| Some(s.trim().to_string()).filter(|s| !s.is_empty());

    let mut elements = Vec::new();
    for record in reader.records() {
        let record = record.expect("Invalid CSV record");
        let Ok(id) = record[c_id].trim().parse::<u16>() else {
            continue;
        };
        let name = record[c_name].trim();
        let data_type = record[c_type].trim();
        if name.is_empty() || data_type.is_empty() || NON_ELEMENT_NAMES.contains(&name) {
            continue;
        }
        elements.push(IanaInformationElement {
            id,
            name: name.to_string(),
            data_type: data_type.to_string(),
            semantics: non_empty(&record[c_sem]),
            status: record[c_status].trim().to_string(),
            units: non_empty(&record[c_units]),
        });
    }
    elements.sort_by_key(|e| e.id);
    elements
}

/// The implemented Information Element table, in the same shape as the IANA rows
fn implemented_elements() -> Vec<IanaInformationElement> {
    INFORMATION_ELEMENTS
        .iter()
        .map(|ie| IanaInformationElement {
            id: ie.id,
            name: ie.name.to_string(),
            data_type: ie.data_type.name().to_string(),
            semantics: ie.semantics.map(|s| s.name().to_string()),
            status: match ie.status {
                Status::Current => "current",
                Status::Deprecated => "deprecated",
                Status::Obsolete => "obsolete",
            }
            .to_string(),
            units: ie.units.map(str::to_string),
        })
        .collect()
}

/// `unsigned64` -> `Unsigned64`, `ipv4Address` -> `Ipv4Address`
fn variant(name: &str) -> String {
    let mut chars = name.chars();
    match chars.next() {
        Some(first) => first.to_uppercase().chain(chars).collect(),
        None => String::new(),
    }
}

/// Render `src/registry/information_elements.rs` (rustfmt-stable output)
pub fn render_information_elements(elements: &[IanaInformationElement]) -> String {
    let mut out = String::new();
    out.push_str(
        "//! IANA IPFIX Information Elements\n\
         //!\n\
         //! @generated by `make registry-update` from\n\
         //! <https://www.iana.org/assignments/ipfix/ipfix-information-elements.csv>.\n\
         //! Do not edit by hand: `make specs-validate` checks this table against IANA.\n\
         \n\
         use super::{DataType, DataTypeSemantics, InformationElement, Status};\n\
         \n\
         /// All IANA-assigned Information Elements, sorted by ElementID\n\
         pub const INFORMATION_ELEMENTS: &[InformationElement] = &[\n",
    );
    for e in elements {
        let semantics = match &e.semantics {
            Some(s) => format!("Some(DataTypeSemantics::{})", variant(s)),
            None => "None".to_string(),
        };
        let units = match &e.units {
            Some(u) => format!("Some({:?})", u),
            None => "None".to_string(),
        };
        writeln!(
            out,
            "    InformationElement {{\n        id: {},\n        name: {:?},\n        \
             data_type: DataType::{},\n        semantics: {},\n        status: Status::{},\n        \
             units: {},\n    }},",
            e.id,
            e.name,
            variant(&e.data_type),
            semantics,
            variant(&e.status),
            units
        )
        .unwrap();
    }
    out.push_str("];\n");
    out
}

/// Extract `(value, name)` records of an IANA XML sub-registry
pub fn parse_iana_xml_registry(xml: &str, registry_id: &str) -> Vec<(String, String)> {
    let start = xml
        .find(&format!("<registry id=\"{}\"", registry_id))
        .unwrap_or_else(|| panic!("Registry {} not found", registry_id));
    let block = &xml[start..];
    let block = &block[..block.find("</registry>").unwrap()];
    let record =
        Regex::new(r"(?s)<record[^>]*>\s*<value>([^<]*)</value>\s*<(?:description|name)>([^<]*)</")
            .unwrap();
    record
        .captures_iter(block)
        .map(|c| (c[1].trim().to_string(), c[2].trim().to_string()))
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    const CSV_SAMPLE: &str = "ElementID,Name,Abstract Data Type,Data Type Semantics,Status,Description,Units,Range,Additional Information,Reference,Revision,Date
0,Reserved,,,,,,,,[RFC 5102],,2013-02-18
1,octetDeltaCount,unsigned64,deltaCounter,current,\"The number of octets
over several lines.\",octets,,,[RFC 5102],0,2013-02-18
97,Assigned for NetFlow v9 compatibility,,,,,,,,[RFC 5102],,2013-02-18
105-127,Assigned for NetFlow v9 compatibility,,,,,,,,[RFC 5102],,2013-02-18
416,,,,deprecated,,,,,,,
";

    #[test]
    fn test_parse_iana_csv() {
        let elements = parse_iana_csv(CSV_SAMPLE);
        assert_eq!(
            elements,
            vec![IanaInformationElement {
                id: 1,
                name: "octetDeltaCount".to_string(),
                data_type: "unsigned64".to_string(),
                semantics: Some("deltaCounter".to_string()),
                status: "current".to_string(),
                units: Some("octets".to_string()),
            }]
        );
    }

    #[test]
    fn test_render_information_elements() {
        let rendered = render_information_elements(&parse_iana_csv(CSV_SAMPLE));
        assert!(rendered.contains("data_type: DataType::Unsigned64,"));
        assert!(rendered.contains("semantics: Some(DataTypeSemantics::DeltaCounter),"));
        assert!(rendered.contains("units: Some(\"octets\"),"));
    }

    /// Regenerate `src/registry/information_elements.rs` from IANA.
    ///
    /// Only runs with `IPFIX_REGENERATE=1` (`make registry-update`), so that
    /// `--ignored` runs in CI never overwrite the table they validate.
    #[test]
    #[ignore] // Requires network access
    fn generate_information_elements() {
        if std::env::var("IPFIX_REGENERATE").as_deref() != Ok("1") {
            println!("Skipping: set IPFIX_REGENERATE=1 to regenerate the registry");
            return;
        }
        let elements = parse_iana_csv(&fetch(&IANA_INFORMATION_ELEMENTS));
        let path =
            Path::new(env!("CARGO_MANIFEST_DIR")).join("src/registry/information_elements.rs");
        std::fs::write(&path, render_information_elements(&elements))
            .expect("Failed to write registry");
        println!(
            "Wrote {} Information Elements to {}",
            elements.len(),
            path.display()
        );
    }

    #[test]
    #[ignore] // Requires network access
    fn test_validate_information_elements() {
        let iana: BTreeMap<u16, IanaInformationElement> =
            parse_iana_csv(&fetch(&IANA_INFORMATION_ELEMENTS))
                .into_iter()
                .map(|e| (e.id, e))
                .collect();
        let implemented: BTreeMap<u16, IanaInformationElement> = implemented_elements()
            .into_iter()
            .map(|e| (e.id, e))
            .collect();

        println!("\n=== IANA Information Elements Validation ===\n");
        let mut issues = Vec::new();
        for (id, expected) in &iana {
            match implemented.get(id) {
                None => issues.push(format!("⬜ ({}) {} missing", id, expected.name)),
                Some(actual) if actual != expected => issues.push(format!(
                    "⚠️ ({}) {} differs:\n     IANA:        {:?}\n     implemented: {:?}",
                    id, expected.name, expected, actual
                )),
                Some(_) => {}
            }
        }
        for (id, actual) in &implemented {
            if !iana.contains_key(id) {
                issues.push(format!("❌ ({}) {} not in IANA registry", id, actual.name));
            }
        }

        let deprecated = iana.values().filter(|e| e.status == "deprecated").count();
        println!("IANA Information Elements: {}", iana.len());
        println!("Implemented: {}", implemented.len());
        println!("Deprecated: {}", deprecated);

        if !issues.is_empty() {
            for issue in &issues {
                println!("{}", issue);
            }
            panic!(
                "Information Element registry validation failed: {} issue(s). \
                 Run `make registry-update` to regenerate the table from IANA.",
                issues.len()
            );
        }
        println!("\n✅ All {} Information Elements match IANA", iana.len());
    }

    #[test]
    #[ignore] // Requires network access
    fn test_validate_data_types() {
        let xml = fetch(&IANA_IPFIX_REGISTRY);
        let iana: Vec<_> = parse_iana_xml_registry(&xml, "ipfix-information-element-data-types")
            .into_iter()
            .filter(|(_, name)| name != "Unassigned")
            .collect();
        let implemented: Vec<_> = DataType::ALL
            .iter()
            .map(|t| ((*t as u8).to_string(), t.name().to_string()))
            .collect();
        assert_eq!(
            implemented, iana,
            "DataType does not match the IANA registry"
        );
        println!("✅ {} data types match IANA", iana.len());
    }

    #[test]
    #[ignore] // Requires network access
    fn test_validate_data_type_semantics() {
        let xml = fetch(&IANA_IPFIX_REGISTRY);
        let iana: Vec<_> = parse_iana_xml_registry(&xml, "ipfix-information-element-semantics")
            .into_iter()
            .filter(|(_, name)| name != "Unassigned")
            .collect();
        let implemented: Vec<_> = DataTypeSemantics::ALL
            .iter()
            .map(|s| ((*s as u8).to_string(), s.name().to_string()))
            .collect();
        assert_eq!(
            implemented, iana,
            "DataTypeSemantics does not match the IANA registry"
        );
        println!("✅ {} data type semantics match IANA", iana.len());
    }

    #[test]
    #[ignore] // Requires network access
    fn test_validate_set_ids_and_version() {
        let xml = fetch(&IANA_IPFIX_REGISTRY);

        let set_ids = parse_iana_xml_registry(&xml, "ipfix-set-ids");
        let find = |name: &str| {
            set_ids
                .iter()
                .find(|(_, n)| n == name)
                .unwrap_or_else(|| panic!("Set ID '{}' not in IANA registry", name))
                .0
                .clone()
        };
        assert_eq!(find("Template Set"), TEMPLATE_SET_ID.to_string());
        assert_eq!(
            find("Options Template Set"),
            OPTIONS_TEMPLATE_SET_ID.to_string()
        );
        assert_eq!(
            find("Reserved for Data Sets"),
            format!("{}-65535", MIN_DATA_SET_ID)
        );

        let versions = parse_iana_xml_registry(&xml, "ipfix-version-numbers");
        assert!(
            versions.contains(&(IPFIX_VERSION.to_string(), "IPFIX".to_string())),
            "IPFIX version {} not in IANA registry",
            IPFIX_VERSION
        );
        println!("✅ Set IDs and Version Number match IANA");
    }
}
